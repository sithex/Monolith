import test from 'node:test';
import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
import ts from 'typescript';

const read = path => readFileSync(new URL(`../${path}`, import.meta.url), 'utf8');
const view = read('ui/views/TerminalView.tsx');

// Exercise the actual handler inside the xterm constructor, without mounting a webview/PTY.
function linkHandler(open, fail) {
  const source = ts.createSourceFile('TerminalView.tsx', view, ts.ScriptTarget.Latest, true, ts.ScriptKind.TSX);
  let options;
  function visit(node) {
    if (ts.isNewExpression(node) && node.expression.getText(source) === 'Terminal') options = node.arguments[0];
    ts.forEachChild(node, visit);
  }
  visit(source);
  assert.ok(options && ts.isObjectLiteralExpression(options), 'xterm constructor options exist');
  const handlers = options.properties.filter(property => property.name?.getText(source) === 'linkHandler');
  assert.equal(handlers.length, 1, 'one OSC 8 handler, no second click path');
  const code = ts.transpile(`const handler = ${handlers[0].initializer.getText(source)};`, { target: ts.ScriptTarget.ES2022 });
  return new Function('terminalOpenLink', 'fail', `${code}\nreturn handler;`)(open, fail);
}

test('OSC 8 activation forwards the original URI once through typed IPC', async () => {
  const opened = [];
  const handler = linkHandler(async uri => opened.push(uri), assert.fail);
  const uri = 'https://example.com/path?one=1&two=2#fragment';
  handler.activate({}, uri);
  await Promise.resolve();
  assert.deepEqual(opened, [uri]);
  assert.doesNotMatch(view, /window\.open\s*\(|confirm\s*\(|registerLinkProvider\s*\(|addEventListener\(['"](?:click|mouseup)['"]/);
});

test('OSC 8 IPC refusal reaches the existing error handler', async () => {
  const failure = new Error('Only http(s) links can be opened');
  const errors = [];
  const handler = linkHandler(async () => { throw failure; }, error => errors.push(error));
  handler.activate({}, 'file:///etc/passwd');
  await Promise.resolve();
  assert.deepEqual(errors, [failure]);
});

test('terminal link command is registered end-to-end in the existing island capability', () => {
  assert.match(read('src-tauri/build.rs'), /"terminal_open_link"/);
  assert.match(read('src-tauri/src/lib.rs'), /commands::terminal::terminal_open_link,/);
  assert.match(read('src-tauri/permissions/island.toml'), /"allow-terminal-open-link"/);
  assert.ok(JSON.parse(read('src-tauri/capabilities/island.json')).permissions.includes('island-commands'));
  assert.match(read('src-tauri/permissions/autogenerated/terminal_open_link.toml'), /commands\.allow = \["terminal_open_link"\]/);
  assert.match(read('ui/ipc/bindings.ts'), /terminalOpenLink: \(uri: string\) => .*__TAURI_INVOKE\("terminal_open_link", \{ uri \}\)/);
  assert.match(read('ui/ipc/client.ts'), /export const terminalOpenLink = async \(uri: string\): Promise<void> => \{\s*await unwrap\(commands\.terminalOpenLink\(uri\)\);\s*\}/);
});
